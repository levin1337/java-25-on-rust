const fn spec(name: &'static [u8], signature: &'static [u8]) -> JniMethodSpec {
    JniMethodSpec { name, signature }
}

pub fn find(name: &[u8], signature: &[u8]) -> Option<&'static JniMethodSpec> {
    JNI_METHODS
        .iter()
        .find(|spec| spec.name == name && spec.signature == signature)
}
